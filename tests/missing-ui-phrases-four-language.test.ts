test('Early W/M, Telegram, Replay and sentiment labels have translations in every language', () => {
  for (const source of newLabels) {
    for (const language of supportedLanguages) {
      const phrase = locales[language].phrases[source];
      assert.equal(typeof phrase, 'string', language + ': ' + source);
      assert.ok(phrase.trim().length > 0, language + ': ' + source);
      assert.equal(translatePhrase(language, source).trim(), phrase.trim(), language + ': ' + source);
    }
  }
  assert.equal(translatePhrase('en', 'Зупинити пошук'), 'Stop scan');
  assert.equal(translatePhrase('pl', 'Таймфрейм відтворення'), 'Interwał odtwarzania');
  assert.equal(translatePhrase('ru', 'Telegram: очікує повторної спроби'), 'Telegram: ожидает повторной попытки');
  assert.equal(translatePhrase('uk', 'Лінія шиї'), 'Лінія шиї');
});
